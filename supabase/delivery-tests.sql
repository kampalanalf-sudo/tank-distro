-- Run after both migrations using a project-owner connection. All fixtures roll back.
begin;
do $$
declare
  admin_id uuid := gen_random_uuid(); rider_id uuid := gen_random_uuid(); outsider_id uuid := gen_random_uuid();
  request_id uuid := gen_random_uuid(); token text := encode(extensions.gen_random_bytes(32),'hex');
  receipt jsonb; retry jsonb; tracking jsonb; v_order_id uuid; rejected boolean;
begin
  insert into auth.users(id,email) values(admin_id,admin_id||'@example.invalid'),(rider_id,rider_id||'@example.invalid'),(outsider_id,outsider_id||'@example.invalid');
  insert into public.delivery_staff values(admin_id,'Test administrator','admin',true),(rider_id,'Test rider','rider',true);
  receipt := public.place_delivery_order('Test customer','0772123456','Test address Kampala','Kololo','', '[{"id":2,"quantity":2,"price":1}]'::jsonb,request_id,token);
  v_order_id := (receipt->>'id')::uuid;
  assert (receipt->>'total')::integer = 49000, 'Server must ignore client prices';
  retry := public.place_delivery_order('Test customer','0772123456','Test address Kampala','Kololo','', '[{"id":2,"quantity":2}]'::jsonb,request_id,token);
  assert receipt->>'id' = retry->>'id', 'Idempotent retries must not duplicate orders';
  tracking := public.track_delivery_order(v_order_id,token);
  assert tracking->>'status' = 'received';
  assert not (tracking ? 'phone') and not (tracking ? 'address') and not (tracking ? 'tracking_hash'), 'Tracking must not expose private customer data';
  rejected := false;
  begin perform public.track_delivery_order(v_order_id,repeat('a',64)); exception when others then rejected := true; end;
  assert rejected, 'Wrong tracking token must be rejected';
  perform set_config('request.jwt.claim.sub',outsider_id::text,true);
  rejected := false;
  begin perform public.assign_delivery_rider(v_order_id,rider_id); exception when others then rejected := true; end;
  assert rejected, 'Non-staff cannot assign a rider';
  rejected := false;
  begin perform public.update_delivery_status(v_order_id,'confirmed','received'); exception when others then rejected := true; end;
  assert rejected, 'Non-staff cannot update progress';
  perform set_config('request.jwt.claim.sub',admin_id::text,true);
  rejected := false;
  begin perform public.update_delivery_status(v_order_id,'preparing','received'); exception when others then rejected := true; end;
  assert rejected, 'Progress cannot skip a stage';
  perform public.update_delivery_status(v_order_id,'confirmed','received');
  perform public.update_delivery_status(v_order_id,'preparing','confirmed');
  perform public.update_delivery_status(v_order_id,'ready','preparing');
  rejected := false;
  begin perform public.update_delivery_status(v_order_id,'on_the_way','ready'); exception when others then rejected := true; end;
  assert rejected, 'Dispatch requires rider assignment';
  perform public.assign_delivery_rider(v_order_id,rider_id);
  perform set_config('request.jwt.claim.sub',rider_id::text,true);
  rejected := false;
  begin perform public.share_delivery_location(v_order_id,0.33,32.59,12,now()); exception when others then rejected := true; end;
  assert rejected, 'GPS cannot start before dispatch';
  perform public.update_delivery_status(v_order_id,'on_the_way','ready');
  perform public.share_delivery_location(v_order_id,0.33,32.59,12,now());
  tracking := public.track_delivery_order(v_order_id,token);
  assert (tracking->'location'->>'latitude')::numeric = 0.33, 'Tracking receives assigned rider GPS';
  assert (tracking->'location'->>'sharing')::boolean;
  perform set_config('request.jwt.claim.sub',outsider_id::text,true);
  rejected := false;
  begin perform public.share_delivery_location(v_order_id,0.34,32.60,12,now()); exception when others then rejected := true; end;
  assert rejected, 'Another account cannot publish rider GPS';
  perform set_config('request.jwt.claim.sub',rider_id::text,true);
  perform public.stop_delivery_location(v_order_id);
  tracking := public.track_delivery_order(v_order_id,token);
  assert not (tracking->'location'->>'sharing')::boolean, 'Stopping GPS marks sharing off';
  perform public.update_delivery_status(v_order_id,'delivered','on_the_way');
  assert not exists(select 1 from public.delivery_locations where delivery_locations.order_id = v_order_id), 'Completion removes GPS';
  rejected := false;
  begin perform public.share_delivery_location(v_order_id,0.33,32.59,12,now()); exception when others then rejected := true; end;
  assert rejected, 'GPS cannot restart after completion';
  assert not has_table_privilege('anon','public.delivery_orders','SELECT'), 'Guest table access must be denied';
  assert not has_table_privilege('authenticated','public.delivery_orders','UPDATE'), 'Raw updates must be denied';
  assert not has_function_privilege('anon','public.assign_delivery_rider(uuid,uuid)','EXECUTE'), 'Guests cannot execute staff RPCs';
  assert (select bool_and(rowsecurity) from pg_tables where schemaname='public' and tablename like 'delivery_%'), 'Every delivery table must have RLS';
end $$;
rollback;
select 'Backend assertions passed; all test orders, GPS and users rolled back.' as result;
